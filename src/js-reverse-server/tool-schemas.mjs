const missingToolArgumentMaps = Object.keys(TOOL_DEFINITIONS)
  .filter((name) => !Object.hasOwn(TOOL_ARGUMENTS, name));
const unknownToolArgumentMaps = Object.keys(TOOL_ARGUMENTS)
  .filter((name) => !Object.hasOwn(TOOL_DEFINITIONS, name));
if (missingToolArgumentMaps.length > 0 || unknownToolArgumentMaps.length > 0) {
  throw new Error(`js-reverse tool schema map mismatch: missing=${missingToolArgumentMaps.join(",")} unknown=${unknownToolArgumentMaps.join(",")}`);
}

const TOOL_SCHEMAS = Object.fromEntries(
  Object.entries(TOOL_DEFINITIONS).map(([name, description]) => {
    const properties = Object.fromEntries(TOOL_ARGUMENTS[name].map((propertyName) => {
      const definition = PROPERTY_DEFINITIONS[propertyName];
      if (!definition) throw new Error(`js-reverse tool ${name} references unknown property ${propertyName}`);
      return [propertyName, definition];
    }));
    return [name, {
      description,
      inputSchema: {
        type: "object",
        properties,
        additionalProperties: false,
      },
    }];
  }),
);

